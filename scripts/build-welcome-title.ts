// Bakes the onboarding greeting into SVG outlines, so the browser can trace
// it glyph by glyph without loading the script face. Writes
// src/components/Onboarding/welcomeTitlePaths.ts; run with
// `npm run build:welcome-title` after changing the text or the font.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';

const TEXT = 'Welcome to PaperTok';
const FONT_SIZE = 160;
// Room round the outlines so the viewBox does not clip an edge.
const PAD = 4;
const OUT = new URL('../src/components/Onboarding/welcomeTitlePaths.ts', import.meta.url);

const require = createRequire(import.meta.url);
const fontFile = require.resolve('@fontsource/pinyon-script/files/pinyon-script-latin-400-normal.woff');
const { version } = JSON.parse(readFileSync(require.resolve('@fontsource/pinyon-script/package.json'), 'utf8'));
const { attribution } = JSON.parse(readFileSync(require.resolve('@fontsource/pinyon-script/metadata.json'), 'utf8')).license;
const bytes = readFileSync(fontFile);
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));

const baseline = Math.round((font.ascender / font.unitsPerEm) * FONT_SIZE);
const round = value => Math.round(value * 10) / 10;
// The script's slant, for the reveal that follows the pen along it. Baked
// into the data as `slant` so the component leans its bands the same way.
const SLANT_DEGREES = 22;
const SLANT = Math.tan((SLANT_DEGREES * Math.PI) / 180);
const CURVE_SEGMENTS = 16;

// The outline as points, curves cut into straight segments: enough for the
// outline's length and for the glyph's extent across the slant.
function flatten(commands) {
  const points = [];
  let start = null;
  let last = null;
  for (const c of commands) {
    if (c.type === 'M') {
      last = start = [c.x, c.y];
      points.push({ point: last, move: true });
    } else if (c.type === 'L') {
      last = [c.x, c.y];
      points.push({ point: last });
    } else if (c.type === 'Q' || c.type === 'C') {
      const [x0, y0] = last;
      for (let step = 1; step <= CURVE_SEGMENTS; step += 1) {
        const t = step / CURVE_SEGMENTS;
        const u = 1 - t;
        const point = c.type === 'Q'
          ? [u * u * x0 + 2 * u * t * c.x1 + t * t * c.x, u * u * y0 + 2 * u * t * c.y1 + t * t * c.y]
          : [
            u ** 3 * x0 + 3 * u * u * t * c.x1 + 3 * u * t * t * c.x2 + t ** 3 * c.x,
            u ** 3 * y0 + 3 * u * u * t * c.y1 + 3 * u * t * t * c.y2 + t ** 3 * c.y,
          ];
        points.push({ point });
      }
      last = [c.x, c.y];
    } else if (c.type === 'Z' && start) {
      last = start;
      points.push({ point: start });
    }
  }
  return points;
}

function outlineLength(points) {
  let length = 0;
  for (let index = 1; index < points.length; index += 1) {
    if (points[index].move) continue;
    const [ax, ay] = points[index - 1].point;
    const [bx, by] = points[index].point;
    length += Math.hypot(bx - ax, by - ay);
  }
  return length;
}

const glyphs = [];
let afterSpace = false;
let x1 = Infinity, y1 = Infinity, x2 = -Infinity, y2 = -Infinity;
const chars = [...TEXT];
let index = 0;
font.forEachGlyph(TEXT, 0, baseline, FONT_SIZE, { kerning: true }, (glyph, gx, gy) => {
  const char = chars[index++];
  if (char === ' ') {
    afterSpace = true;
    return;
  }
  const path = glyph.getPath(gx, gy, FONT_SIZE);
  const box = path.getBoundingBox();
  x1 = Math.min(x1, box.x1); y1 = Math.min(y1, box.y1);
  x2 = Math.max(x2, box.x2); y2 = Math.max(y2, box.y2);
  const points = flatten(path.commands);
  // Across the slant: x measured along lines leaning as the script does,
  // pivoting on the baseline, which is where the reveal's edge runs.
  const across = points.map(({ point: [px, py] }) => px + SLANT * (py - baseline));
  glyphs.push({
    char,
    d: path.toPathData(1),
    x: round(gx),
    box: [round(box.x1), round(box.x2)],
    sweep: [round(Math.min(...across)), round(Math.max(...across))],
    length: round(outlineLength(points)),
    ...(afterSpace ? { afterSpace: true } : {}),
  });
  afterSpace = false;
});
if (index !== chars.length) throw new Error('One glyph per character was expected; the text needs ligature-aware mapping.');

const viewBox = [x1 - PAD, y1 - PAD, x2 - x1 + 2 * PAD, y2 - y1 + 2 * PAD].map(value => Math.floor(value * 10) / 10).join(' ');

const source = `// GENERATED by scripts/build-welcome-title.ts; do not edit by hand.
// "${TEXT}" in Pinyon Script (@fontsource/pinyon-script ${version}), ${FONT_SIZE} units
// to the em, one outline per visible glyph in writing order. The outlines are
// derived from the font: ${attribution}, licensed under the
// SIL Open Font License 1.1 (node_modules/@fontsource/pinyon-script/LICENSE).
// Per glyph: \`x\` its origin, \`box\` its horizontal extent, \`sweep\` its
// extent across the \`slant\` (degrees) pivoting on the baseline (where the reveal's
// leaning edge travels), \`length\` its outline length, curves cut into
// ${CURVE_SEGMENTS} segments. \`afterSpace\` marks the first glyph of a word after the first.

export default ${JSON.stringify({ text: TEXT, viewBox, baseline, slant: SLANT_DEGREES, glyphs }, null, 2)};
`;
writeFileSync(OUT, source);
console.log(`Wrote ${OUT.pathname} (${source.length} bytes, ${glyphs.length} glyphs).`);
