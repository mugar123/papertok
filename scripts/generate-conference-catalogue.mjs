import { readFileSync, writeFileSync } from 'node:fs';

const path = process.argv[2];
if (!path) throw new Error('Usage: node scripts/generate-conference-catalogue.mjs path/to/catalogo-final.json');
const { rules, conferences } = JSON.parse(readFileSync(path, 'utf8'));
const { reject_cues_regex, strict_regex, organisations, plain_uppercase_words, strict_archives } = rules;
// Comments about an unsuccessful submission or a side event
// can name the main conference and year without placing this paper there.
const extraReject = String.raw`submission\b|withdrawn|not\s+accepted|affinity|student abstracts?|\b(?:companion|adjunct|SRW)\b|\b(?:position(?: paper)?|research|industr(?:y|ial))[- ]tracks?\b|reproducibility|\bblog\s?posts?\b|\btiny\s?papers?\b|\bLBW\b`;
// These catalogue titles omit “symposium” or use the venue's former name.
const symposiumTitles = new Map([
  ['GD', 'Symposium on Graph Drawing'],
  ['NSDI', 'Symposium on Networked Systems Design and Implementation'],
  ['OSDI', 'Symposium on Operating Systems Design and Implementation'],
  ['CSFW', 'Computer Security Foundations Symposium'],
  ['CGO', 'Symposium on Code Generation and Optimization'],
]);
const symposiumAliases = new Map([
  ['S7407086454', ['symposium on wearable computing']],
  ['S4306420590', ['network and distributed systems security symposium']],
  ['S7407088775', ['symposium on cluster, cloud and internet computing']],
]);
const venueAliases = new Map([
  ['VLDB', ['PVLDB']],
  ['NeurIPS', ['Advances in Neural Information Processing Systems', 'Conference on Neural Information Processing Systems']],
]);
const termSpellings = new Map([['GLOBECOM', ['Globecom']]]);
// Bare acronyms shared by conferences in different fields. Keep the full venue spellings.
const primaryCategories = new Map([
  ['FSE', ['cs.SE']], // Fast Software Encryption
  ['SA', ['cs.GR']], // Software Architecture and AAAI Student Abstracts
  ['SP', ['cs.CR']], // Signal Processing
  ['IV', ['cs.RO']], // International Conference on Information Visualisation
  ['CEC', ['cs.NE']], // IEEE Conference on Commerce and Enterprise Computing
  ['SDM', ['cs.DB', 'cs.IR', 'cs.LG']], // Structures, Structural Dynamics, and Materials
  ['HT', ['cs.HC', 'cs.IR']], // ASME Heat Transfer Summer Conference
]);
const excludedCategories = new Map([
  ['SAC', ['cs.CR', 'quant-ph']], // Selected Areas in Cryptography
]);
const seenIds = new Set();
const rows = conferences.map(({ id, label, name, terms, disambiguation }) => {
  if (!id || !label || seenIds.has(id)) throw new Error(`Invalid or duplicate conference: ${id}`);
  seenIds.add(id);
  // Titles sometimes include a publisher prefix, alternate title or trailing acronym.
  const title = (symposiumTitles.get(label) ?? name).replace(/\s*\([^()]+\)$/, '');
  const symposium = title.split('/').find(part => /\bsymposium\b/i.test(part))?.toLowerCase()
    .replace(/^.*?\b(symposium on )/, '$1').replace(/^(?:(?:ieee|acm|international)\s+)+/, '');
  return JSON.stringify({
    id, label, name, ...(name.includes('Workshop') && { workshop: true }),
    ...(symposium && { symposiumNames: [symposium, ...(symposiumAliases.get(id) ?? [])] }),
    aliases: venueAliases.get(label),
    terms: terms.flatMap(({ text, match, allowed_before, reject_if_comment_has, only_arxiv_categories, not_arxiv_categories }) => {
      if (!text || !['strict', 'distinct', 'phrase'].includes(match)) throw new Error(`Invalid term for ${id}: ${text}`);
      return [text, ...(termSpellings.get(text) ?? [])].map(spelling => ({ text: spelling, match, allowed_before,
        reject_if_comment_has, only_arxiv_categories: primaryCategories.get(text) ?? only_arxiv_categories,
        not_arxiv_categories: excludedCategories.get(text) ?? not_arxiv_categories, disambiguation: disambiguation?.[text] }));
    }),
  });
});
const [workshop, ...otherCues] = reject_cues_regex.split('|');
if (workshop !== 'workshop') throw new Error('Expected workshop as the first rejection cue');
const withoutWorkshop = [...otherCues, extraReject].join('|');
const matchRules = { reject_cues_regex: [reject_cues_regex, extraReject].join('|'), reject_except_workshop: withoutWorkshop, strict_regex, organisations, plain_uppercase_words, strict_archives };
const output = `// Generated by scripts/generate-conference-catalogue.mjs. The catalogue supplies venue terms and baseline rules.\n// The generator adds rejection cues, category restrictions and venue aliases. See accepted-conference.ts for attribution.
import type { Conference } from './accepted-conference.ts';

export const rules = ${JSON.stringify(matchRules, null, 2)};
export const conferences: Conference[] = [
  ${rows.join(',\n  ')},
];
`;
writeFileSync(new URL('../worker/conference-catalogue.generated.ts', import.meta.url), output);
